"""
Generates the fine-tuning dataset for the Vistral-7B shopping assistant.

Two data sources are combined:
  1. REAL product data pulled straight from the marketplace's own PostgreSQL
     database (so the model actually learns the shop's real catalog style),
     turned into simple template-based Q&A pairs (no LLM call needed, free).
  2. SYNTHETIC conversational variety generated by calling the OpenAI API a
     limited number of times (paraphrases, multi-turn follow-ups, edge cases
     like "san pham nay het hang chua", "co size lon hon khong") so the model
     doesn't just memorize one phrasing per product.

Output: data/train.jsonl and data/eval.jsonl in the chat format Vistral/TRL expects:
  {"messages": [{"role": "system", ...}, {"role": "user", ...}, {"role": "assistant", ...}]}

Run this LOCALLY or on Colab before training (needs read access to the same
Postgres DB the Spring Boot backend uses, and OPENAI_API_KEY for step 2 only).
"""

import json
import os
import random
import time

import psycopg2
import psycopg2.extras

# ---- config ----
DB_DSN = os.environ.get("MARKETPLACE_DB_DSN", "postgresql://postgres:postgres@localhost:5432/marketplace")
OUTPUT_DIR = os.path.join(os.path.dirname(__file__), "..", "data")
N_SYNTHETIC_PER_PRODUCT = 3          # how many extra paraphrased Q&A per product to generate via API
EVAL_SPLIT_RATIO = 0.1               # 10% held out for evaluation
RANDOM_SEED = 42

SYSTEM_PROMPT = (
    "Ban la tro ly tu van mua sam cho mot san thuong mai dien tu da nguoi ban. "
    "Chi duoc tra loi dua tren thong tin san pham duoc cung cap. Khong duoc bia dat "
    "thong tin ngoai pham vi. Tra loi ngan gon, than thien, bang tieng Viet."
)

# ---- 1. Template-based Q&A from real DB rows (free, no API calls) ----

TEMPLATES = [
    ("{name} gia bao nhieu?", "{name} hien co gia {price} VND, ban tai shop {shop}."),
    ("San pham {name} con hang khong?", "{name} hien con {stock} san pham trong kho."),
    ("Cho toi hoi ve {name}.", "{name}: {description_short} Gia {price} VND, con {stock} san pham."),
    ("{name} thuoc danh muc gi?", "{name} thuoc danh muc {category}, ban boi shop {shop}."),
]


def fetch_products(conn):
    with conn.cursor(cursor_factory=psycopg2.extras.RealDictCursor) as cur:
        cur.execute("""
            SELECT p.name, p.description, p.price, p.stock,
                   s.name AS shop_name, c.name AS category_name
            FROM products p
            JOIN shops s ON p.shop_id = s.id
            LEFT JOIN categories c ON p.category_id = c.id
            WHERE p.active = true
        """)
        return cur.fetchall()


def build_template_examples(products):
    examples = []
    for p in products:
        desc_short = (p["description"] or "")[:120]
        for q_tpl, a_tpl in TEMPLATES:
            question = q_tpl.format(name=p["name"])
            answer = a_tpl.format(
                name=p["name"],
                price=p["price"],
                shop=p["shop_name"],
                stock=p["stock"],
                category=p["category_name"] or "chua phan loai",
                description_short=desc_short or "San pham chat luong tot.",
            )
            examples.append({
                "messages": [
                    {"role": "system", "content": SYSTEM_PROMPT},
                    {"role": "user", "content": question},
                    {"role": "assistant", "content": answer},
                ]
            })
    return examples


# ---- 2. Synthetic paraphrases via OpenAI (adds conversational variety) ----

def build_synthetic_examples(products, n_per_product):
    """Calls OpenAI to paraphrase questions in more natural, varied Vietnamese.
    Skipped automatically if OPENAI_API_KEY is not set (template data alone is
    still usable, just less varied)."""
    api_key = os.environ.get("OPENAI_API_KEY")
    if not api_key:
        print(">> OPENAI_API_KEY not set - skipping synthetic augmentation, using templates only.")
        return []

    from openai import OpenAI
    client = OpenAI(api_key=api_key)

    examples = []
    for p in products:
        prompt = (
            f"San pham: {p['name']}\n"
            f"Mo ta: {p['description'] or 'khong co'}\n"
            f"Gia: {p['price']} VND, con {p['stock']} san pham, shop {p['shop_name']}.\n\n"
            f"Hay viet {n_per_product} cau hoi tu nhien, da dang cach dien dat ma mot khach hang "
            f"that co the hoi ve san pham nay (vd hoi ve gia, ton kho, chat lieu, cach dung...), "
            f"va cau tra loi tuong ung CHI dua tren thong tin tren. "
            f"Tra ve dung dinh dang JSON: "
            f'[{{"q": "...", "a": "..."}}, ...]'
        )
        try:
            resp = client.chat.completions.create(
                model="gpt-4o-mini",
                messages=[{"role": "user", "content": prompt}],
                temperature=0.8,
            )
            pairs = json.loads(resp.choices[0].message.content)
            for pair in pairs:
                examples.append({
                    "messages": [
                        {"role": "system", "content": SYSTEM_PROMPT},
                        {"role": "user", "content": pair["q"]},
                        {"role": "assistant", "content": pair["a"]},
                    ]
                })
            time.sleep(0.3)  # gentle on rate limits
        except Exception as e:
            print(f"   ! skipped product '{p['name']}' due to error: {e}")
    return examples


def main():
    random.seed(RANDOM_SEED)
    os.makedirs(OUTPUT_DIR, exist_ok=True)

    print(">> Connecting to database...")
    conn = psycopg2.connect(DB_DSN)
    products = fetch_products(conn)
    conn.close()
    print(f">> Fetched {len(products)} active products.")

    if len(products) < 5:
        print("!! WARNING: very few products in DB. Seed more sample products first "
              "(see backend/src/main/java/.../config/DataSeeder.java for the pattern), "
              "otherwise the fine-tuned model will have almost nothing to learn from.")

    template_examples = build_template_examples(products)
    synthetic_examples = build_synthetic_examples(products, N_SYNTHETIC_PER_PRODUCT)

    all_examples = template_examples + synthetic_examples
    random.shuffle(all_examples)

    split_idx = int(len(all_examples) * (1 - EVAL_SPLIT_RATIO))
    train_examples = all_examples[:split_idx]
    eval_examples = all_examples[split_idx:]

    train_path = os.path.join(OUTPUT_DIR, "train.jsonl")
    eval_path = os.path.join(OUTPUT_DIR, "eval.jsonl")

    with open(train_path, "w", encoding="utf-8") as f:
        for ex in train_examples:
            f.write(json.dumps(ex, ensure_ascii=False) + "\n")

    with open(eval_path, "w", encoding="utf-8") as f:
        for ex in eval_examples:
            f.write(json.dumps(ex, ensure_ascii=False) + "\n")

    print(f">> Wrote {len(train_examples)} training examples -> {train_path}")
    print(f">> Wrote {len(eval_examples)} eval examples -> {eval_path}")
    print(">> Template-based:", len(template_examples), "| Synthetic (API):", len(synthetic_examples))


if __name__ == "__main__":
    main()
