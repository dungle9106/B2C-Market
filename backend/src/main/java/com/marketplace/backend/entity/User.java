package com.marketplace.backend.entity;

import com.fasterxml.jackson.annotation.JsonIgnore;
import jakarta.persistence.*;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Data;
import lombok.NoArgsConstructor;

import java.time.LocalDateTime;

// returned as JSON by AdminController: the password hash must never be serialized
@Entity
@Table(name = "users")
@Data
@NoArgsConstructor
@AllArgsConstructor
@Builder
public class User {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @Column(nullable = false, unique = true)
    private String email;

    @JsonIgnore
    @Column(nullable = false)
    private String password; // BCrypt hash

    @Column(nullable = false)
    private String fullName;

    private String phone;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false)
    private Role role;

    // LOCAL = registered with email/password directly in the app
    // GOOGLE = first signed in (and auto-created) via "Login with Google"
    @Enumerated(EnumType.STRING)
    // DB-level default so ddl-auto=update can add this NOT NULL column to a
    // users table that already has rows (they become LOCAL accounts)
    @Builder.Default
    @Column(nullable = false, length = 20, columnDefinition = "varchar(20) default 'LOCAL'")
    private AuthProvider authProvider = AuthProvider.LOCAL;

    @Builder.Default
    private boolean enabled = true;

    // ==== moderation by an admin ====
    @Column(length = 500)
    private String lockedReason;

    private LocalDateTime lockedAt;

    // null = locked until an admin unlocks; otherwise unlocked automatically after this time
    private LocalDateTime lockedUntil;

    // "deleted" accounts are anonymised, not removed: their orders and reviews must stay consistent
    private LocalDateTime deletedAt;

    private LocalDateTime lastLoginAt;

    // ==== admin staff ====
    // the owner account: every permission, can manage other admins
    @Builder.Default
    @Column(nullable = false, columnDefinition = "boolean default false")
    private boolean superAdmin = false;

    // comma-separated AdminPermission names of a staff admin
    @Column(length = 300)
    private String adminPermissions;

    // ==== account security ====
    @Builder.Default
    @Column(nullable = false, columnDefinition = "integer default 0")
    private int failedLoginCount = 0;      // wrong passwords in a row

    private LocalDateTime loginLockedUntil;  // automatic short lock after too many wrong passwords

    @Builder.Default
    @Column(nullable = false, columnDefinition = "boolean default false")
    private boolean emailVerified = false;

    private LocalDateTime passwordChangedAt;

    // two-step verification (TOTP, e.g. Google Authenticator); the secret is encrypted (SecretCipher)
    @Builder.Default
    @Column(nullable = false, columnDefinition = "boolean default false")
    private boolean totpEnabled = false;

    @Column(length = 200)
    private String totpSecret;

    @Column(length = 200)
    private String totpPendingSecret;      // generated by "setup", becomes totpSecret once a code is confirmed

    @Column(length = 1000)
    private String backupCodes;            // SHA-256 of the unused one-time backup codes, comma separated

    @Column(updatable = false)
    private LocalDateTime createdAt;

    @PrePersist
    public void prePersist() {
        this.createdAt = LocalDateTime.now();
    }
}
